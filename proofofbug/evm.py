"""Run transaction sequences on the REAL contracts (Foundry EVM) and return traces.

The generated Foundry test deploys every contract at the same small address the circuit
uses (by running its creation code in place), optionally puts a programmable attacker
contract at the attacker's address, then runs each sequence from a clean state and
writes one line per transaction: success, first return word, and every watched slot.
"""
from __future__ import annotations
import json, os, subprocess

FORGE = os.environ.get("FORGE", "forge")

ATTACKER_SRC = r'''
// A user account with code: when called during a transaction it makes one call back
// into whoever called it (the plan), then stays quiet.
contract GGAttacker {
    bytes plan;
    bool armed;
    function ggArm(bytes calldata p) external { plan = p; armed = true; }
    function ggDisarm() external { armed = false; }
    fallback() external payable {
        if (armed) { armed = false; (bool ok, ) = msg.sender.call(plan); ok; }
    }
}
'''

RUNNER = r'''// SPDX-License-Identifier: MIT
// Generated by Proof of Bug. Executes sequences from gg-out/{tag}.in.json on the real EVM.
pragma solidity ^0.8.20;
{imports}

interface Vm {{
    function prank(address) external;
    function warp(uint256) external;
    function deal(address, uint256) external;
    function load(address, bytes32) external view returns (bytes32);
    function etch(address, bytes calldata) external;
    function snapshotState() external returns (uint256);
    function revertToState(uint256) external returns (bool);
    function readFile(string calldata) external view returns (string memory);
    function parseJsonUintArray(string calldata, string calldata) external pure returns (uint256[] memory);
    function writeLine(string calldata, string calldata) external;
    function toString(uint256) external pure returns (string memory);
    function toString(bytes calldata) external pure returns (string memory);
    function toString(address) external pure returns (string memory);
    function parseBytes(string calldata) external pure returns (bytes memory);
}}
{attacker_src}
contract GGRun_{tag} {{
    Vm constant vm = Vm(address(uint160(uint256(keccak256("hevm cheat code")))));
    string constant OUT = "gg-out/{tag}.out.csv";

    function deployAt(bytes memory creation, address where) internal {{
        vm.etch(where, creation);  // (a cheatcode: a pending prank applies to the constructor call below)
        (bool ok, bytes memory runtime) = where.call("");
        require(ok, "constructor reverted");
        vm.etch(where, runtime);
    }}

    function setup() internal {{
{deploys}
    }}

    function snap(uint256[] memory d) internal view returns (string memory s) {{
        for (uint256 i = 0; i < d[0]; i++) {{
            address a = address(uint160(d[1 + 2 * i]));
            uint256 v = d[2 + 2 * i] == type(uint256).max ? a.balance : uint256(vm.load(a, bytes32(d[2 + 2 * i])));
            s = string.concat(s, ",", vm.toString(v));
        }}
    }}

    function calldata_(uint256[] memory d, uint256 p) internal pure returns (uint256, bytes memory cd) {{
        cd = abi.encodePacked(bytes4(uint32(d[p++])));
        uint256 n = d[p++];
        for (uint256 a = 0; a < n; a++) cd = abi.encodePacked(cd, d[p++]);
        return (p, cd);
    }}

    function call1(uint256[] memory d, uint256 p) internal returns (uint256, bool, bytes memory) {{
        address to = address(uint160(d[p++]));
        address sender = address(uint160(d[p++]));
        bytes memory cd;
        (p, cd) = calldata_(d, p);
        uint256 hookOn = d[p++];
        bytes memory hook;
        (p, hook) = calldata_(d, p);
        vm.warp(d[p++]);
        uint256 value = d[p++];
{arm}
        if (value > sender.balance) return (p, false, "");  // not a valid transaction (the model rejects it too)
        // under prank the value comes out of the sender's own balance (as on a real chain)
        vm.prank(sender);
        (bool ok, bytes memory r) = to.call{{value: value}}(cd);
        return (p, ok, r);
    }}

    // one sequence per external call, so each gets fresh memory
    function runCase(uint256[] calldata dc, uint256 p, uint256 c) external returns (uint256) {{
        uint256[] memory d = dc;
        vm.warp(1);
        setup();
        if (c == 0) {{
{codes}
        }}
        vm.writeLine(OUT, string.concat(vm.toString(c), ",init,1,0,0", snap(d)));
        uint256 ntx = d[p++];
        for (uint256 j = 0; j < ntx; j++) {{
            bool ok; bytes memory r;
            (p, ok, r) = call1(d, p);
            string memory s = string.concat(vm.toString(c), ",", vm.toString(j), ",", ok ? "1" : "0");
            s = string.concat(s, ",", vm.toString(r.length >= 32 ? abi.decode(r, (uint256)) : 0));
            s = string.concat(s, ",", vm.toString(r.length), snap(d));
            vm.writeLine(OUT, s);
        }}
        return p;
    }}

    function test_run() public {{
        uint256[] memory d = vm.parseJsonUintArray(vm.readFile("gg-out/{tag}.in.json"), ".d");
        uint256 p = 1 + 2 * d[0];
        uint256 ncases = d[p++];
        uint256 clean = vm.snapshotState();
        for (uint256 c = 0; c < ncases; c++) {{
            vm.revertToState(clean);
            p = this.runCase(d, p, c);
        }}
    }}
}}
'''


def run(cfg, tag, sequences, watch, chunk=40):
    """Run sequences in batches of `chunk` (one Foundry test per batch: a test has a fixed gas budget,
    and every sequence redeploys the case and snapshots every watched slot)."""
    if len(sequences) <= chunk:
        return _run(cfg, tag, sequences, watch)
    out = []
    for i in range(0, len(sequences), chunk):
        part = _run(cfg, f"{tag}_{i // chunk}", sequences[i:i + chunk], watch)
        if i and part:
            part[0].pop("code", None)
        out += part
    return out


def _run(cfg, tag, sequences, watch):
    """cfg: {"root", "imports": [paths relative to test/gg], "deploys": [(name, address, ctor_args_expr)],
    "attacker": address or None}. sequences: lists of {to, selector, sender, args, hook}.
    watch: [(address, slot)]. Returns per sequence {"init": {(a,s): v}, "txs": [...]}."""
    root = cfg["root"]
    os.makedirs(os.path.join(root, "gg-out"), exist_ok=True)
    os.makedirs(os.path.join(root, "test", "gg"), exist_ok=True)
    d = [len(watch)]
    for a, s in watch:
        d += [a, s]
    d.append(len(sequences))
    for seq in sequences:
        d.append(len(seq))
        for tx in seq:
            d += [tx["to"], tx["sender"], tx["selector"], len(tx["args"])] + list(tx["args"])
            h = tx.get("hook")
            d += [1, h["selector"], len(h["args"])] + list(h["args"]) if h else [0, 0, 0]
            d.append(tx.get("time", 1))
            d.append(tx.get("value", 0))
    json.dump({"d": d}, open(os.path.join(root, "gg-out", f"{tag}.in.json"), "w"))
    out = os.path.join(root, "gg-out", f"{tag}.out.csv")
    if os.path.exists(out):
        os.remove(out)
    att = cfg.get("attacker")
    # deploy the creation code of OUR compilation (the one the circuit is built from), so the
    # bytecode on the EVM and the model agree, immutables included
    order = cfg.get("order") or list(range(len(cfg["deploys"])))
    lines = []
    for i in order:
        n, a, args = cfg["deploys"][i][:3]
        code = cfg.get("bytecode", {}).get(n)
        if code:
            path = f"gg-out/code_{tag}_{n}.hex"  # per run: parallel runs and same-named contracts never share a file
            open(os.path.join(root, path), "w").write("0x" + code)
            creation = f'vm.parseBytes(vm.readFile("{path}"))'
        else:
            creation = f"type({n}).creationCode"
        who = f"vm.prank({cfg['deployer']}); " if cfg.get("deployer") else ""
        lines.append(f"        {who}deployAt(abi.encodePacked({creation}, {args}), address({hex(a)}));")
    deploys = "\n".join(lines)
    codes = "\n".join(f'            vm.writeLine(OUT, string.concat("code,", vm.toString(address({hex(a)}).code)));'
                      for n, a, _ in cfg["deploys"])
    for a, amount in cfg.get("eth", []):  # ETH held at the start (users' wallets, funded contracts)
        deploys += f"\n        vm.deal(address({hex(a)}), {amount});"
    for stmt in cfg.get("setup", []):  # setup calls from the case's deployment notes
        deploys += f"\n        {stmt}"
    if att:
        deploys += f"\n        vm.etch(address({hex(att)}), type(GGAttacker).runtimeCode);"
        arm = (f"        if (hookOn == 1) GGAttacker(payable(address({hex(att)}))).ggArm(hook);\n"
               f"        else GGAttacker(payable(address({hex(att)}))).ggDisarm();")
    else:
        arm = "        hookOn; hook;"
    imports = "\n".join(f'import "{p}";' for p in dict.fromkeys(cfg["imports"]))
    src = RUNNER.format(tag=tag, imports=imports, deploys=deploys, arm=arm, codes=codes,
                        attacker_src=ATTACKER_SRC if att else "")
    runner = os.path.join(root, "test", "gg", f"Run_{tag}.t.sol")
    open(runner, "w").write(src)
    try:
        p = subprocess.run([FORGE, "test", "--match-contract", f"GGRun_{tag}$"], cwd=root, capture_output=True, text=True)
    finally:
        os.remove(runner)  # generated runners are one-shot; leaving them makes every later build slower
    if p.returncode != 0 or not os.path.exists(out):
        raise RuntimeError(f"forge failed:\n{p.stdout[-3000:]}\n{p.stderr[-3000:]}")
    traces = [{"init": None, "txs": []} for _ in sequences]
    codes = []
    for line in open(out):
        f = line.strip().split(",")
        if f[0] == "code":
            codes.append(f[1])
            continue
        c, j = int(f[0]), f[1]
        vals = {w: int(v) for w, v in zip(watch, f[5:])}
        if j == "init":
            traces[c]["init"] = vals
        else:
            traces[c]["txs"].append({"ok": f[2] == "1", "ret": int(f[3]), "retlen": int(f[4]), "slots": vals})
    if traces:
        traces[0]["code"] = {a: codes[i] for i, (n, a, _) in enumerate(cfg["deploys"]) if i < len(codes)}
    return traces
